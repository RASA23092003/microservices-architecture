CREATE TABLE CARD(
	CARD_ID VARCHAR(16) PRIMARY KEY,
	NAME_ON_CARD VARCHAR(50),
	CVV VARCHAR(70),
	CARD_TYPE ENUM('DEBIT_CARD','CREDIT_CARD'),
	EXPIRY_DATE DATE,
	CUSTOMER_ID INT
);
